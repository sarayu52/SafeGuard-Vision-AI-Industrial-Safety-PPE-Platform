import React, { useState, useEffect } from 'react';
import {
  UserCheck,
  ShieldCheck,
  ShieldAlert,
  AlertTriangle,
  Building2,
  Clock,
  Info,
  ExternalLink,
} from 'lucide-react';
import { api } from '../services/api';
import { WorkerTrack } from '../types';

interface WorkerTrackAnalysisProps {
  onNavigateToReport: (id: string) => void;
}

export const WorkerTrackAnalysis: React.FC<WorkerTrackAnalysisProps> = ({ onNavigateToReport }) => {
  const [tracks, setTracks] = useState<WorkerTrack[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    loadTracks();
  }, []);

  const loadTracks = async () => {
    try {
      const res = await api.getWorkerTracks();
      setTracks(res);
    } catch (err) {
      console.error('Failed to load tracks:', err);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="p-6 max-w-7xl mx-auto space-y-6">
      {/* Header Banner */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 p-5 bg-white border border-slate-200 rounded-xl shadow-xs">
        <div>
          <h2 className="text-base font-semibold text-slate-900 flex items-center gap-2">
            <UserCheck className="w-5 h-5 text-teal-600" />
            Worker &amp; Visual Track Longitudinal Analysis
          </h2>
          <p className="text-xs text-slate-500 mt-1">
            Tracks temporary visual object identifiers across video streams without assigning real human identities.
          </p>
        </div>
      </div>

      {/* Privacy Notice Banner */}
      <div className="p-4 rounded-xl bg-blue-50 border border-blue-200 text-blue-900 text-xs flex items-start gap-3">
        <Info className="w-4 h-4 text-blue-600 shrink-0 mt-0.5" />
        <div>
          <p className="font-semibold">Privacy &amp; Algorithmic Identification Policy:</p>
          <p className="text-[11px] text-blue-800 mt-0.5">
            Track identifiers (e.g., Track 01, Track 04) are temporary visual computer-vision bounding box trajectories generated by YOLOv8 and ByteTrack. The system strictly analyzes equipment compliance without facial recognition or employee biometric tracking.
          </p>
        </div>
      </div>

      {/* Track Cards Grid */}
      {loading ? (
        <div className="p-12 text-center text-xs text-slate-500">Loading worker visual tracks...</div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
          {tracks.map((track) => {
            const isCompliant = track.complianceRate >= 95;
            const isCritical = track.riskLevel === 'Critical';

            return (
              <div
                key={track.trackId}
                className="p-5 bg-white border border-slate-200 rounded-2xl shadow-xs space-y-4 flex flex-col justify-between"
              >
                <div>
                  <div className="flex items-center justify-between border-b border-slate-100 pb-3">
                    <span className="text-xs font-mono font-bold text-slate-900 bg-slate-100 px-2 py-0.5 rounded">
                      {track.trackId}
                    </span>
                    <span className={`text-[10px] font-bold px-1.5 py-0.5 rounded ${
                      isCritical
                        ? 'bg-red-100 text-red-700'
                        : isCompliant
                        ? 'bg-emerald-100 text-emerald-700'
                        : 'bg-amber-100 text-amber-700'
                    }`}>
                      {track.riskLevel} Risk
                    </span>
                  </div>

                  <div className="space-y-2 mt-3">
                    <p className="text-xs text-slate-600 flex items-center gap-1.5">
                      <Building2 className="w-3.5 h-3.5 text-slate-400" />
                      <span className="truncate">{track.siteName}</span>
                    </p>

                    <div className="p-3 bg-slate-50 rounded-xl space-y-1">
                      <div className="flex justify-between text-xs">
                        <span className="text-slate-500 font-medium">Compliance Rate</span>
                        <span className="font-bold text-slate-900">{track.complianceRate}%</span>
                      </div>
                      <div className="w-full bg-slate-200 rounded-full h-1.5 overflow-hidden">
                        <div
                          className={`h-1.5 rounded-full ${
                            track.complianceRate >= 90 ? 'bg-emerald-500' : 'bg-red-500'
                          }`}
                          style={{ width: `${track.complianceRate}%` }}
                        />
                      </div>
                    </div>

                    <div className="text-[11px] space-y-1 pt-1">
                      <div className="flex justify-between text-slate-600">
                        <span>Total Observations:</span>
                        <span className="font-semibold text-slate-900">{track.totalObservations} Frames</span>
                      </div>
                      <div className="flex justify-between text-slate-600">
                        <span>Violations Flagged:</span>
                        <span className="font-semibold text-red-600">{track.violationsCount}</span>
                      </div>
                      <div className="flex justify-between text-slate-600">
                        <span>Primary Concern:</span>
                        <span className="font-medium text-slate-800 truncate max-w-[140px]">
                          {track.primaryViolation}
                        </span>
                      </div>
                    </div>
                  </div>
                </div>

                <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-[10px] text-slate-400">
                  <span className="flex items-center gap-1">
                    <Clock className="w-3 h-3" />
                    Seen {track.lastSeen}
                  </span>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
